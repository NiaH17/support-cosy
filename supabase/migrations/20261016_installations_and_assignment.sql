-- 1. Which admin is speaking to the installer
ALTER TABLE fr_support_requests
  ADD COLUMN IF NOT EXISTS assigned_admin_id   uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS assigned_admin_name text;

-- 2. Install registrations
CREATE TABLE IF NOT EXISTS fr_installations (
  id                      uuid PRIMARY KEY,                       -- generated by the app so photos can be filed under it
  created_at              timestamptz NOT NULL DEFAULT now(),
  user_id                 uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  user_email              text,
  install_date            date NOT NULL,
  address                 text NOT NULL,
  lead_engineer           text NOT NULL,
  partner_contractor      text,
  model                   text NOT NULL,
  outdoor_serial          text NOT NULL,
  indoor_serial           text,
  hub_serial              text NOT NULL,
  checks                  jsonb NOT NULL DEFAULT '{}'::jsonb,     -- { key: true/false }
  photos                  jsonb NOT NULL DEFAULT '{}'::jsonb,     -- { key: [storage paths] }
  engineer_signature_path text,
  engineer_signed_on      date,
  customer_signature_path text,
  customer_signed_on      date,
  declaration_accepted    boolean NOT NULL DEFAULT false,
  email_sent              boolean NOT NULL DEFAULT false
);

CREATE INDEX IF NOT EXISTS fr_installations_created_idx ON fr_installations (created_at DESC);
CREATE INDEX IF NOT EXISTS fr_installations_user_idx ON fr_installations (user_id);

ALTER TABLE fr_installations ENABLE ROW LEVEL SECURITY;

-- Installers read their own; admins read all. Inserts go through /api/submit-installation (service role).
DROP POLICY IF EXISTS "Users read own installations" ON fr_installations;
CREATE POLICY "Users read own installations" ON fr_installations
  FOR SELECT TO authenticated USING (auth.uid() = user_id);

DROP POLICY IF EXISTS "Admins read all installations" ON fr_installations;
CREATE POLICY "Admins read all installations" ON fr_installations
  FOR SELECT TO authenticated USING (public.is_admin());

-- 3. Private storage for install photos and signatures (files live under <user id>/<install id>/)
INSERT INTO storage.buckets (id, name, public) VALUES ('install-photos', 'install-photos', false)
ON CONFLICT (id) DO NOTHING;

DROP POLICY IF EXISTS "install-photos upload own folder" ON storage.objects;
CREATE POLICY "install-photos upload own folder" ON storage.objects
  FOR INSERT TO authenticated
  WITH CHECK (bucket_id = 'install-photos' AND (storage.foldername(name))[1] = auth.uid()::text);

DROP POLICY IF EXISTS "install-photos read own or admin" ON storage.objects;
CREATE POLICY "install-photos read own or admin" ON storage.objects
  FOR SELECT TO authenticated
  USING (bucket_id = 'install-photos' AND ((storage.foldername(name))[1] = auth.uid()::text OR public.is_admin()));
